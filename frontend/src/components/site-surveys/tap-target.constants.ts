/**
 * @fileoverview タップ領域の下限（44 論理ピクセル）の単一の出所
 *
 * 要件28.3 は「モバイル幅ツールバーの各項目のタップ領域を最小44x44論理ピクセル以上の
 * サイズで提供する」と定める。要件29.4・34.5・35.5 はいずれも同じ数値を
 * 「Requirement 28.3 と整合」として引いており、**仕様の側では 44 の出所は 28.3 の一箇所**
 * である。本モジュールはそれを実装の側でも一箇所にする。
 *
 * ただし**本モジュールを参照する箇所のすべてが要件に課されているわけではない**。
 * `PendingUploadPanel`（要件37 が所管。同要件はタップ領域の受入基準を持たない）と
 * `AnnotationContextMenu`（要件27 が所管。同要件も条項を持たない）は 28.3 の条文の対象外
 * である。**この二つの根拠は受入基準ではなく、`.kiro/steering/tech.md` の
 * 「レスポンシブ・ビューポート方針」が定める「モバイルの下限値」**（操作系コントロールの
 * タップ領域は最小 44×44 論理ピクセル。WCAG 2.2 SC 2.5.5）**という横断ルールである**
 * （タスク 115.246 で決着。requirements.md の要件28 の注記を参照）。同方針は新規画面・
 * コンポーネントにも及ぶため、受入基準へ写し取らずに参照してよい。根拠は各参照箇所の注釈
 * にも記した。
 *
 * ## 実装はここを参照する。検証は 44 を自前で持つ（タスク 115.217 の判断）
 *
 * 本定数を**取り込んでよいのは画面を描く側だけ**である。検証（単体テスト・E2E）は
 * 44 を自前で書く。次の担当者が「検証も取り込めば重複が消える」と考えるのは自然だが、
 * それは下限の主張を同語反復にする。次の二つの変異を実行して確かめた。
 *
 * - 本定数を 44 から 20 へ変えて
 *   `npm --prefix frontend run test -- --run src/__tests__/components/site-surveys src/__tests__/site-surveys`
 *   を実行すると、89 ファイル 2473 件のうち 8 ファイル 27 件が落ちる（2026-08-31 実測。
 *   変異前は 89 ファイル 2473 件すべて緑）。実装を一箇所へ集めても検証は追随している。
 * - 同じ 20 のまま、`AnnotationToolbar.mobile-tap-target.test.tsx` の
 *   `const TAP_TARGET_MIN_PX = 44;` を本モジュールからの取り込みへ置き換えて
 *   当該ファイルだけを走らせると、落ちるのは 22 件中 1 件だけになる（2026-08-31 実測。
 *   自前で 44 を持つときは 22 件中 11 件が落ちる）。残る 1 件は `'44px'` を直に書いた
 *   別の主張であり、取り込んだ名前を使う 10 件は**20px を描いたまま緑になる**。
 *
 * つまり取り込みは「実装が下限を満たす」という主張を「実装は実装に等しい」へ弱める。
 *
 * **技術的な制約ではない。** E2E からも `frontend/src` は取り込める。実例として
 * `e2e/specs/site-surveys/site-survey-responsive.spec.ts` は
 * `frontend/src/services/AutoSaveManager` の `DEFAULT_AUTO_SAVE_INTERVAL_MS` を取り込み、
 * 同じファイルの中で 44 だけは自前で持っている。この二つの扱いの違いは、できるかどうか
 * ではなく次節の理由による。
 *
 * ## タスク 115.183（自動保存の間隔）と結論が逆になる理由
 *
 * タスク 115.183 は `services/AutoSaveManager.ts` の `DEFAULT_AUTO_SAVE_INTERVAL_MS` を
 * export した。間隔は**実装が選ぶ値**であり外部の権威を持たないため、検証は実装の選択に
 * 同意するほかなく、複製すると間隔の変更に検証だけが追随せず古い前提のまま緑になる。
 *
 * 44 は性質が違う。これは要件28.3 の条文が運ぶ値であり（要件28 の注記のとおり WCAG 2.2 の
 * 達成基準 2.5.5 の水準）、実装が調整する余地を持たない。**外部の権威が定めた下限は、
 * 実装から独立した立会人が測らなければ検証にならない。** よって同一バッチの二つの判断
 * （115.183 は export、115.170 は複製）は矛盾ではなく、値の性質による使い分けである。
 *
 * ## 名前は一つに揃える（タスク 115.217 で是正）
 *
 * 同じ概念に `TAP_TARGET_MIN_PX` / `MIN_TAP_TARGET_PX` / `TOUCH_TARGET_MIN_PX` の三つの
 * 名前が並立していた。実装・検証のどちらでも `TAP_TARGET_MIN_PX` を使う。名前が一つなら、
 * 複製を意図的に残していても母集団を名前で引ける。
 *
 * ## 母集団の走査（後任はこのコマンドで数え直すこと）
 *
 * ```
 * grep -rnE "(^|[^0-9])44([^0-9]|$)" --include=*.ts --include=*.tsx \
 *   frontend/src/components/site-surveys frontend/src/__tests__/components/site-surveys \
 *   frontend/src/__tests__/site-surveys e2e/specs/site-surveys
 * ```
 *
 * 上記の走査は 2026-09-02 時点で 21 ファイル 159 行に当たる（うち 18 行は本ファイル自身に
 * 当たる。内訳は説明文 17 行と `export` の宣言 1 行である。**記録を書き足す行為そのものが
 * 件数を動かすため、後任は測り直すこと**。実際、タスク 115.246 が本ファイルと参照元の注釈へ
 * 根拠を書き足したことで 2026-08-31 時点の 157 行から 2 行増えている）。
 * 残りのうち 7 行は寸法とは無関係な
 * `1.44`（`DimensionTool.label-outline.test.ts` 6 行・`annotation-style-tokens.test.ts` 1 行）
 * であり、残りがタップ領域の 44 である。実装の側（`frontend/src/components/site-surveys/`）で
 * 下限を課す箇所は本モジュールを参照する。上の走査を注釈行以外へ絞る
 * （`| grep -vE "^\S+: *(\*|//|/\*)"`）と、当該ディレクトリで 44 を綴る行は本ファイルの
 * `export` 一行だけになる（2026-08-31 実測）。この範囲の外は保証しない。検証の側に
 * 残る 44 は上記の理由による意図的な複製である。
 * `frontend/src/components/construction-photos/` にも 44 の主張があるが、別スペックの
 * 所有物であり本モジュールの射程外である。
 */

